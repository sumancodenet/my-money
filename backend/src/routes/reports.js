import { Router } from 'express';
import { monthlyReport, yearlyReport, bankWiseReport, categoryWiseReport, exportPdf, exportExcel } from '../controllers/reportController.js';
import { protect } from '../middlewares/authMiddleware.js';
import { cacheable, invalidateUserCache } from '../middlewares/cache.js';
const router = Router();
router.use(protect);
router.use(invalidateUserCache);
router.get('/monthly', cacheable(60), monthlyReport);
router.get('/yearly', cacheable(60), yearlyReport);
router.get('/bank-wise', cacheable(60), bankWiseReport);
router.get('/category-wise', cacheable(60), categoryWiseReport);
router.get('/export/pdf', exportPdf);
router.get('/export/excel', exportExcel);
export default router;
